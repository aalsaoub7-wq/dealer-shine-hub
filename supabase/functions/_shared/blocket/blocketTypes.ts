  id: string;
  company_id: string;
  user_id: string;
  make: string;
  model: string;
  year: number;
  mileage: number | null;
  fuel: string | null;
  gearbox: string | null;
  price: number | null;
  description: string | null;
  notes: string | null;
  registration_number: string | null;
  vin: string | null;
  color: string | null;
  image_urls: string[];
  publish_on_blocket: boolean;
  deleted_at: string | null;
  created_at: string;
  updated_at: string;
